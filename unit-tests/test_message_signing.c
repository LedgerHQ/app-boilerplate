#define HD HARDENED_BIP32

static void init_path(bip44_path_t* dst, const uint32_t* elems, size_t len) {
    dst->length = len;
    for (size_t i = 0; i < len; i++) {
        dst->path[i] = elems[i];
    }
}

static void test_sign_raw_message(void **state) {
    (void) state;
    bip44_path_t path = {0};
    init_path(&path, (uint32_t[]){HD + 1852, HD + 1815, HD + 0, 0, 1}, 5);

    const uint8_t message[] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
                               0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};
    uint8_t signature[ED25519_SIGNATURE_LENGTH] = {0};
    size_t sigLen = sizeof(signature);

    assert_int_equal(CX_OK,
                     signRawMessageWithPath(&path, message, sizeof(message), signature, sigLen));

    const uint8_t expected[] = {
        0x82, 0x0a, 0x1b, 0x6a, 0xe0, 0x17, 0x4b, 0xd0, 0x7e, 0x2a, 0xff, 0x14, 0x7e, 0x81, 0x11, 0x35,
        0x68, 0x63, 0x2b, 0x8e, 0x2a, 0x44, 0x71, 0x1b, 0x7d, 0x7c, 0x81, 0x0d, 0x54, 0xb5, 0xc6, 0x7a,
        0x9b, 0x65, 0x46, 0xb5, 0xd8, 0x4d, 0xb1, 0x19, 0xc6, 0x67, 0x26, 0x62, 0xf4, 0xd4, 0xca, 0xa8,
        0x73, 0x75, 0xbb, 0xd1, 0xad, 0x76, 0x4e, 0x44, 0x09, 0x5a, 0x32, 0x20, 0x5a, 0x84, 0x11, 0x0f,
    };
    assert_memory_equal(signature, expected, sizeof(expected));
}

