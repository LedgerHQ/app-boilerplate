static void run_sign_tx_fixture(const sign_tx_fixture_t *fixture) {
    reset_context();
    assert_true(app_mem_init());

    uint8_t init_raw[512];
    size_t init_len = hex_to_bytes(fixture->init_hex, init_raw, sizeof(init_raw));
    buffer_t init_buf = {
        .ptr = init_raw,
        .size = init_len,
        .offset = 0,
    };
    assert_int_equal(handler_sign_tx(&init_buf, P1_TX_INIT, false), 0);
    assert_int_equal(G_context.req_type, REQUEST_SIGN_TRANSACTION);
    assert_int_equal(G_context.state.tx_state, TX_STATE_CHUNKS);
    assert_int_equal(G_context.tx_info.num_witnesses, fixture->expected_num_witnesses);

    for (size_t i = 0; i < fixture->chunk_count; i++) {
        const apdu_segment_t *segment = &fixture->chunks[i];
        uint8_t chunk_raw[512];
        size_t chunk_len = hex_to_bytes(segment->hex_payload, chunk_raw, sizeof(chunk_raw));
        buffer_t chunk_buf = {
            .ptr = chunk_raw,
            .size = chunk_len,
            .offset = 0,
        };
        assert_int_equal(handler_sign_tx(&chunk_buf, segment->p1, segment->more), SW_OK);
    }

    uint8_t tx_body_raw[50000];
    assert_non_null(fixture->tx_body_cbor_hex);
    size_t tx_body_len = hex_to_bytes(fixture->tx_body_cbor_hex, tx_body_raw, sizeof(tx_body_raw));

    uint8_t expected_hash[TX_HASH_LENGTH];
    assert_int_equal(blake2b(expected_hash, TX_HASH_LENGTH, tx_body_raw, tx_body_len), 0);
    assert_int_equal(g_last_response_len, TX_HASH_LENGTH);
    assert_memory_equal(g_last_response, expected_hash, TX_HASH_LENGTH);
    assert_int_equal(g_last_response_sw, SW_OK);
    assert_int_equal(G_context.req_type, REQUEST_NONE);

    tx_context_cleanup();
}

static void test_sign_tx_fixture_case(void **state) {
    const sign_tx_fixture_t *fixture = (const sign_tx_fixture_t *) *state;
    assert_non_null(fixture);
    if (fixture->skip_reason != NULL) {
        print_message("[SKIP] %s: %s\n", fixture->name, fixture->skip_reason);
        skip();
    }
    run_sign_tx_fixture(fixture);
}

int main(void) {
    const size_t test_count = ARRAY_LEN(SIGN_TX_FIXTURES);
    struct CMUnitTest tests[ARRAY_LEN(SIGN_TX_FIXTURES)];
    for (size_t i = 0; i < test_count; i++) {
        tests[i] = (struct CMUnitTest) {
            .name = SIGN_TX_FIXTURES[i].name,
            .test_func = test_sign_tx_fixture_case,
            .setup_func = NULL,
            .teardown_func = NULL,
            .initial_state = (void *) &SIGN_TX_FIXTURES[i],
        };
    }
    return _cmocka_run_group_tests("test_sign_tx_handler", tests, test_count, NULL, NULL);
}
